-- ============================================================
-- 艺账 · 数据库表结构（schema.sql）
-- 目标数据库：CloudBase 环境自带的 PostgreSQL 17（无需额外开通）
-- 设计依据：api-contract.md 的「数据模型」一节
-- 关系：categories ← entries ← shots（分类挂账目，账目挂截图）
--
-- 可重复执行：先按依赖倒序 DROP（带 CASCADE）再重建。
--   ⚠️ 会清空原有数据，只用于开发阶段。
-- 执行顺序：先跑本文件（建表），再跑 seed.sql（插示例数据）。
--
-- 【与 MySQL 写法的三处差异，值得记住】
--   1. 自增主键用 IDENTITY，不是 AUTO_INCREMENT；
--   2. 没有 `ON UPDATE CURRENT_TIMESTAMP`，updated_at 由后端接口在 UPDATE 时显式写入（Day 17+ 接口里实现）；
--   3. 字符串定长/变长、金额用 NUMERIC(10,2)（对应 MySQL 的 DECIMAL(10,2)），语义一致。
-- ============================================================

DROP TABLE IF EXISTS shots CASCADE;
DROP TABLE IF EXISTS entries CASCADE;
DROP TABLE IF EXISTS categories CASCADE;

-- ------------------------------------------------------------
-- 1. 分类表：支持「/」分隔的多级路径，如 餐饮/水果
-- ------------------------------------------------------------
CREATE TABLE categories (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  parent_id  BIGINT       NULL REFERENCES categories (id) ON DELETE SET NULL,
  name       VARCHAR(50)  NOT NULL,
  full_path  VARCHAR(255) NOT NULL UNIQUE,
  sort_no    INTEGER      NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

COMMENT ON TABLE  categories            IS '分类（支持多级路径）';
COMMENT ON COLUMN categories.parent_id  IS '上级分类 id；顶级分类为 NULL';
COMMENT ON COLUMN categories.name       IS '本级名称，如「水果」';
COMMENT ON COLUMN categories.full_path  IS '完整路径，如「餐饮/水果」（与前端一致的存法）';
COMMENT ON COLUMN categories.sort_no    IS '同级排序，数字小的排前面';

CREATE INDEX idx_categories_parent ON categories (parent_id);

-- ------------------------------------------------------------
-- 2. 账目表：一笔花销
-- ------------------------------------------------------------
CREATE TABLE entries (
  id          BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  category_id BIGINT        NULL REFERENCES categories (id) ON DELETE SET NULL,
  spent_on    DATE          NOT NULL,
  item        VARCHAR(100)  NOT NULL,
  amount      NUMERIC(10,2) NOT NULL CHECK (amount >= 0),
  created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
  updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now()
);

COMMENT ON TABLE  entries             IS '账目（一笔花销）';
COMMENT ON COLUMN entries.category_id IS '分类 id；删分类时置空 = 退回未分类';
COMMENT ON COLUMN entries.spent_on    IS '花销日期（按时间段统计靠它）';
COMMENT ON COLUMN entries.item        IS '购买的物资（前端可自动起名，故不允许空）';
COMMENT ON COLUMN entries.amount      IS '金额，单位：元，两位小数';

CREATE INDEX idx_entries_spent_on ON entries (spent_on);
CREATE INDEX idx_entries_category ON entries (category_id);

-- ------------------------------------------------------------
-- 3. 截图表：每笔账目下的支付截图
-- ------------------------------------------------------------
CREATE TABLE shots (
  id         BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entry_id   BIGINT       NOT NULL REFERENCES entries (id) ON DELETE CASCADE,
  seq        INTEGER      NOT NULL DEFAULT 1,
  file_path  VARCHAR(255) NOT NULL,
  width      INTEGER      NULL,
  height     INTEGER      NULL,
  created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
  CONSTRAINT uk_shots_entry_seq UNIQUE (entry_id, seq)
);

COMMENT ON TABLE  shots           IS '每笔账目的支付截图';
COMMENT ON COLUMN shots.entry_id  IS '所属账目 id；删账目时连带删除截图';
COMMENT ON COLUMN shots.seq       IS '同一笔内的第几张（拼图左右顺序）';
COMMENT ON COLUMN shots.file_path IS '图片路径（云存储相对路径）';
COMMENT ON COLUMN shots.width     IS '图片宽（像素）';
COMMENT ON COLUMN shots.height    IS '图片高（像素）';
